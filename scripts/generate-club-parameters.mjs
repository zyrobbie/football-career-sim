import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import readXlsxFile from 'read-excel-file/node'

const workbookPath = 'outputs/club-parameters-v1/俱乐部完整参数表V1.xlsx'
const outputPath = 'src/data/clubs/clubParametersV1.ts'
const legacyMapPath = 'src/data/clubs/legacyClubIdMap.ts'
const expectedClubCount = 366

function fail(message) {
  throw new Error(`Club parameter generation failed: ${message}`)
}

async function loadWorkbookIdToCanonicalRuntimeId() {
  const source = await fs.readFile(legacyMapPath, 'utf8')
  const objectMatch = source.match(
    /WORKBOOK_ID_TO_CANONICAL_RUNTIME_ID\s*=\s*Object\.freeze\(\{([\s\S]*?)\}\s+as const\)/,
  )
  if (!objectMatch?.[1]) fail(`could not read ${legacyMapPath}`)

  const entries = [...objectMatch[1].matchAll(
    /^\s+([a-z0-9_]+): '([a-z0-9_]+)',$/gm,
  )]
  const mapping = new Map(entries.map(([, workbookId, runtimeId]) => [workbookId, runtimeId]))
  if (mapping.size !== 40) fail(`expected 40 manually verified legacy mappings, received ${mapping.size}`)
  return mapping
}

async function readClubRows(workbookIdToRuntimeId) {
  const worksheetRows = await readXlsxFile(workbookPath, { sheet: '参数总表' })
  const rows = worksheetRows.slice(4, 370)
  if (rows.length !== expectedClubCount) fail(`expected ${expectedClubCount} rows, received ${rows.length}`)

  const workbookIds = new Set()
  const runtimeIds = new Set()
  const clubs = rows.map((row, index) => {
    const rowNumber = index + 5
    const [serial, workbookId, country, league, divisionLevel, name, platformTier,
      facility, academy, wage, exposure, firstTeamThreshold, youthPlayerPreference,
      , , , , sourceId] = row

    if (serial !== index + 1) fail(`row ${rowNumber} has serial ${String(serial)}`)
    for (const [field, value] of Object.entries({ workbookId, country, league, name, sourceId })) {
      if (typeof value !== 'string' || value.length === 0) fail(`row ${rowNumber} has empty ${field}`)
    }
    if (!Number.isInteger(divisionLevel) || ![1, 2].includes(divisionLevel)) {
      fail(`row ${rowNumber} has invalid divisionLevel`)
    }
    if (!Number.isInteger(platformTier) || platformTier < 1 || platformTier > 6) {
      fail(`row ${rowNumber} has invalid platformTier`)
    }
    for (const [field, value] of Object.entries({
      facility, academy, wage, exposure, firstTeamThreshold, youthPlayerPreference,
    })) {
      if (!Number.isFinite(value) || value < 0 || value > 100) {
        fail(`row ${rowNumber} has invalid ${field}`)
      }
    }
    if (workbookIds.has(workbookId)) fail(`duplicate workbookId ${workbookId}`)
    workbookIds.add(workbookId)

    const id = workbookIdToRuntimeId.get(workbookId) ?? workbookId
    if (runtimeIds.has(id)) fail(`duplicate canonical runtime id ${id}`)
    runtimeIds.add(id)

    return {
      id,
      workbookId,
      country,
      league,
      divisionLevel,
      name,
      platformTier,
      facility,
      academy,
      wage,
      exposure,
      firstTeamThreshold,
      youthPlayerPreference,
      sourceId,
    }
  })

  for (const workbookId of workbookIdToRuntimeId.keys()) {
    if (!workbookIds.has(workbookId)) fail(`legacy mapping refers to unknown workbookId ${workbookId}`)
  }
  return clubs
}

function render(clubs) {
  const records = clubs
    .map((club) => `  Object.freeze(${JSON.stringify(club)}),`)
    .join('\n')
  return `import type { ClubParametersV1 } from './types'\n\n/**\n * Generated by scripts/generate-club-parameters.mjs from\n * outputs/club-parameters-v1/俱乐部完整参数表V1.xlsx, 参数总表 rows 5-370.\n * It reads only A-M and R. Workbook N/O formulas are intentionally excluded.\n */\nexport const CLUB_PARAMETERS_V1: readonly Readonly<ClubParametersV1>[] = Object.freeze([\n${records}\n])\n`
}

function firstDifferences(expected, actual, limit = 8) {
  const expectedLines = expected.split('\n')
  const actualLines = actual.split('\n')
  const differences = []
  const maxLength = Math.max(expectedLines.length, actualLines.length)
  for (let index = 0; index < maxLength && differences.length < limit; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      differences.push(`line ${index + 1}: expected ${JSON.stringify(expectedLines[index] ?? '')}; current ${JSON.stringify(actualLines[index] ?? '')}`)
    }
  }
  return differences
}

const checkOnly = process.argv.includes('--check')
const workbookIdToRuntimeId = await loadWorkbookIdToCanonicalRuntimeId()
const expected = render(await readClubRows(workbookIdToRuntimeId))
const actual = await fs.readFile(outputPath, 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return null
  throw error
})

if (checkOnly) {
  if (actual !== expected) {
    console.error(`Current ${outputPath} does not match ${workbookPath}.`)
    for (const difference of firstDifferences(expected, actual ?? '')) console.error(difference)
    process.exitCode = 1
  } else {
    console.log(`Verified ${expectedClubCount} club parameters against ${workbookPath}.`)
  }
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, expected)
  console.log(`Generated ${expectedClubCount} club parameters in ${outputPath}.`)
}
